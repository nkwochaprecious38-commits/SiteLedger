"use client";
import { use } from "react";
import Link from "next/link";
import Image from "next/image";
import { ArrowLeft, Printer } from "lucide-react";
import { useApp } from "@/lib/data";
import { Badge, Empty } from "@/components/ui";
import { fmtDate, today } from "@/lib/utils";

export default function ReportPreview({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const { data, company, signedUrl } = useApp();
  const r = data.daily_reports.find((x) => x.id === id);
  if (!r) return <div className="card"><Empty title="Report not found" action={<Link href="/app/reports" className="btn-dark">Back to reports</Link>} /></div>;
  const project = data.projects.find((p) => p.id === r.project_id);
  const history = data.daily_reports.filter((x) => x.project_id === r.project_id).sort((a, b) => b.report_date.localeCompare(a.report_date));
  const Section = ({ title, text }: { title: string; text?: string }) => (
    <div className="border-t border-line py-4"><h3 className="text-xs font-bold uppercase tracking-wide text-muted">{title}</h3><p className="mt-1.5 whitespace-pre-wrap text-sm">{text?.trim() || "None recorded"}</p></div>
  );
  return (
    <div className="mx-auto max-w-4xl">
      <div className="no-print mb-5 flex flex-wrap items-center justify-between gap-3">
        <Link href="/app/reports" className="btn-outline"><ArrowLeft size={16} />All reports</Link>
        <button className="btn-primary" onClick={() => window.print()}><Printer size={16} />Export PDF</button>
      </div>
      <article className="card p-6 sm:p-10">
        <header className="flex flex-wrap items-start justify-between gap-4 border-b-2 border-ink pb-6">
          <div className="flex items-center gap-3"><Image src="/logo.jpg" alt="SiteLedger" width={36} height={44} className="h-11 w-auto" /><div><p className="font-heading text-xl font-extrabold">Daily Site Report</p><p className="text-sm text-muted">{company?.name}</p></div></div>
          <div className="text-right"><p className="font-bold">{fmtDate(r.report_date)}</p><Badge>{r.status}</Badge></div>
        </header>
        <dl className="grid grid-cols-2 gap-4 py-5 text-sm sm:grid-cols-4">
          {[["Project", project?.name || "Not set"], ["Location", project?.location || "Not set"], ["Site supervisor", r.supervisor || "Not set"], ["Weather", r.weather || "Not set"], ["Workforce present", String(r.workforce)], ["Client", project?.client || "Not set"]].map(([k, v]) => (
            <div key={k}><dt className="text-xs font-bold uppercase tracking-wide text-muted">{k}</dt><dd className="mt-1 font-semibold">{v}</dd></div>))}
        </dl>
        <Section title="Site activities completed" text={r.activities} />
        <Section title="Equipment used" text={r.equipment} />
        <Section title="Materials delivered" text={r.materials_delivered} />
        <Section title="Safety observations" text={r.safety} />
        <Section title="Issues encountered" text={r.issues} />
        <Section title="Delays" text={r.delays} />
        <Section title="Additional notes" text={r.notes} />
        {r.photos?.length > 0 && <div className="border-t border-line py-4"><h3 className="text-xs font-bold uppercase tracking-wide text-muted">Site photographs ({r.photos.length})</h3>
          <ul className="no-print mt-2 flex flex-wrap gap-2">{r.photos.map((p: string) => <li key={p}><button className="btn-outline btn-sm" onClick={async () => { const u = await signedUrl(p); if (u) window.open(u, "_blank"); }}>{p.split("/").pop()?.replace(/^\d+_/, "")}</button></li>)}</ul>
          <p className="mt-2 hidden text-sm print:block">{r.photos.length} photograph(s) attached in SiteLedger.</p></div>}
        <footer className="border-t border-line pt-4 text-xs text-muted">Generated by SiteLedger on {fmtDate(today())}</footer>
      </article>
      <section className="no-print mt-8"><h2 className="mb-3 font-bold">Report history for this project</h2>
        <div className="card divide-y divide-line">{history.map((h) => <Link key={h.id} href={`/app/reports/${h.id}`} className={`flex items-center justify-between px-4 py-3 text-sm hover:bg-paper ${h.id === r.id ? "bg-paper font-semibold" : ""}`}><span>{fmtDate(h.report_date)} · {h.supervisor}</span><Badge>{h.status}</Badge></Link>)}</div></section>
    </div>
  );
}
